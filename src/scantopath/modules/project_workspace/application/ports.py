"""07.10: small structural ports for independent project use cases.

Typed DTOs only; no Qt, SQLite or filesystem implementation imports.
New use cases depend on their smallest required protocol, not a fat service.
"""
from __future__ import annotations
from typing import Protocol
from .models import AuditEventSummary, CaptureInspection, ProjectSummary, ProjectTree, ProjectSummary, SpecimenSummary, SessionSummary, CaptureSummary, ProcessingRunSummary, StoreInfo


class ProjectReadPort(Protocol):
    @property
    def info(self) -> StoreInfo: ...
    def list_projects(self) -> tuple[ProjectSummary, ...]: ...
    def get_project_tree(self, project_id: str) -> ProjectTree: ...


class ProjectWritePort(Protocol):
    @property
    def info(self) -> StoreInfo: ...
    def create_project(self, name: str, description: str = "", *, project_id: str | None = None) -> ProjectSummary: ...
    def update_project(self, project_id: str, *, name: str | None = None, description: str | None = None) -> ProjectSummary: ...
    def create_specimen(self, project_id: str, label: str, description: str = "", *, specimen_id: str | None = None) -> SpecimenSummary: ...
    def update_specimen(self, project_id: str, specimen_id: str, *, label: str | None = None, description: str | None = None) -> SpecimenSummary: ...
    def create_session(self, specimen_id: str, label: str = "Scan", *, session_id: str | None = None) -> SessionSummary: ...
    def update_session(self, specimen_id: str, session_id: str, *, label: str | None = None) -> SessionSummary: ...
    def close_session(self, specimen_id: str, session_id: str) -> SessionSummary: ...


class AuditReadPort(Protocol):
    def list_events(self, *, limit: int = 100) -> tuple[AuditEventSummary, ...]: ...


class CaptureInspectionPort(Protocol):
    def inspect_capture(self, capture_id: str) -> CaptureInspection: ...
    def get_capture(self, capture_id: str, *, verify_raw: bool = False) -> CaptureSummary: ...


class ProcessingRunReadPort(Protocol):
    def get_processing_run(self, run_id: str) -> ProcessingRunSummary: ...
